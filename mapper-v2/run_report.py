import sys, json, numpy as np, pandas as pd, matplotlib
matplotlib.use("Agg"); import matplotlib.pyplot as plt
from dataclasses import replace
from mapper import *
CSV = sys.argv[1]; OUT = "figures/"
EV = ["tailgating", "yawn", "eye_close", "eye_off_road", "phone"]            # fixed order = fixed colour
COL = dict(zip(EV, ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]))  # categorical slots 1-5
LAB = {"tailgating": "tailgating (direct)", "yawn": "yawn (derived-weak)", "eye_close": "eye_close (derived-weak)",
       "eye_off_road": "eye_off_road (proxy-weak)", "phone": "phone (proxy-weak)"}
SEQ = {"LOW": "#cfe0f6", "MEDIUM": "#6fa5e8", "HIGH": "#1d4f94"}
INK, GRID = "#0b0b0b", "#e6e5e1"
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.edgecolor": "#8a8984", "axes.labelcolor": "#52514e", "xtick.color": "#52514e",
                     "ytick.color": "#52514e", "axes.grid": True, "grid.color": GRID, "axes.axisbelow": True})
df = load(CSV); trip = df.trip_uuid_

def run(cfg):
    ev, state, aux, prov = map_events(df, cfg); mv = aux.moving
    hrs = mv.sum() / 60; r, st = status_10min(ev, trip, cfg); al = alerts(ev, trip, cfg)
    st = pd.Series(st, index=df.index)
    per_min = st[mv].value_counts(normalize=True).reindex(["LOW", "MEDIUM", "HIGH"]).fillna(0) * 100
    vd_max = r[mv].groupby(df.vday[mv]).max()
    per_vd = pd.Series(np.where(vd_max >= 6, "HIGH", np.where(vd_max >= 3, "MEDIUM", "LOW"))).value_counts(normalize=True) \
               .reindex(["LOW", "MEDIUM", "HIGH"]).fillna(0) * 100
    return dict(ev=ev, aux=aux, hrs=hrs, r=r, st=st, al=al, per_min=per_min, per_vd=per_vd,
                rate={k: ev[k].sum() / hrs for k in EV}, alr={k: al[k].sum() / hrs for k in al},
                vd_alert=al.any(axis=1)[mv].groupby(df.vday[mv]).any().mean() * 100)
base = run(Config()); mv = base["aux"].moving
nvd = df.vday[mv].nunique()
res = {"moving_hours": round(base["hrs"], 1), "vehicle_days": int(nvd),
       "events_per_h": {k: round(v, 3) for k, v in base["rate"].items()},
       "events_total_per_h": round(sum(base["rate"].values()), 3),
       "status_per_minute_pct": base["per_min"].round(2).to_dict(), "status_per_vehicle_day_pct": base["per_vd"].round(1).to_dict(),
       "alerts_per_h_per_vehicle": {k: round(v, 3) for k, v in base["alr"].items()},
       "vehicle_days_with_alert_pct": round(base["vd_alert"], 1)}

# ---------- F1 events per hour
fig, ax = plt.subplots(figsize=(7.5, 3.4)); v = [base["rate"][k] for k in EV][::-1]
ax.barh([LAB[k] for k in EV][::-1], v, color=[COL[k] for k in EV][::-1], height=0.55)
for y, x in enumerate(v): ax.text(x + 0.02, y, f"{x:.2f}", va="center", color=INK, fontsize=9)
ax.set_xlabel("events per moving vehicle-hour"); ax.set_title("Events generated by mapper v2 (714 moving vehicle-hours)", loc="left", color=INK, fontsize=11)
ax.grid(axis="y", visible=False); fig.tight_layout(); fig.savefig(OUT + "f1_events_per_hour.png", dpi=160); plt.close()

# ---------- F2 status distribution (per minute / per vehicle-day)
fig, ax = plt.subplots(figsize=(7.5, 2.6))
for i, (name, s) in enumerate([("per vehicle-day\n(max of the day)", base["per_vd"]), ("per minute", base["per_min"])]):
    left = 0
    for lvl in ["LOW", "MEDIUM", "HIGH"]:
        ax.barh(i, s[lvl], left=left, color=SEQ[lvl], edgecolor="white", linewidth=2, height=0.55,
                label=lvl if i == 0 else None)
        if s[lvl] >= 6: ax.text(left + s[lvl] / 2, i, f"{s[lvl]:.1f}%", ha="center", va="center",
                                color="white" if lvl == "HIGH" else INK, fontsize=9)
        left += s[lvl]
    ax.text(101, i, "", fontsize=8)
ax.set_yticks([0, 1]); ax.set_yticklabels(["per vehicle-day\n(max of the day)", "per minute"]); ax.set_xlim(0, 100)
ax.set_xlabel("% of ..."); ax.legend(ncol=3, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.28))
ax.grid(False); fig.tight_layout(); fig.savefig(OUT + "f2_status_distribution.png", dpi=160); plt.close()

# ---------- F3 priority alerts
fig, ax = plt.subplots(figsize=(7.5, 2.8)); names = list(base["alr"]); vals = [base["alr"][k] for k in names]
cols = [COL["yawn"], COL["eye_close"], COL["phone"], COL["tailgating"]]
ax.barh(names[::-1], vals[::-1], color=cols[::-1], height=0.55)
for y, x in enumerate(vals[::-1]): ax.text(x + 0.01, y, f"{x:.2f}", va="center", fontsize=9, color=INK)
ax.set_xlabel("priority alerts per moving vehicle-hour"); ax.grid(axis="y", visible=False)
ax.set_title(f"Priority alerts (seniors' rules); {base['vd_alert']:.0f}% of vehicle-days have >= 1", loc="left", fontsize=11, color=INK)
fig.tight_layout(); fig.savefig(OUT + "f3_priority_alerts.png", dpi=160); plt.close()

# ---------- F4 per driver heatmap (events/h)
d = df.driver_uuid_; hr = (mv.groupby(d).sum() / 60)
tab = pd.DataFrame({k: base["ev"][k].groupby(d).sum() / hr for k in EV}).fillna(0)
tab.index = [f"driver {i+1} ({hr.iloc[i]:.0f} h)" for i in range(len(tab))]
fig, ax = plt.subplots(figsize=(7.5, 4.2)); im = ax.imshow(tab.values, cmap="Blues", aspect="auto"); ax.grid(False)
ax.set_xticks(range(5)); ax.set_xticklabels(EV, rotation=20); ax.set_yticks(range(len(tab))); ax.set_yticklabels(tab.index)
for i in range(tab.shape[0]):
    for j in range(5): ax.text(j, i, f"{tab.values[i, j]:.2f}", ha="center", va="center", fontsize=8,
                               color="white" if tab.values[i, j] > tab.values.max() * 0.6 else INK)
ax.set_title("Events per moving hour by driver (does one driver dominate?)", loc="left", fontsize=11, color=INK)
fig.tight_layout(); fig.savefig(OUT + "f4_per_driver.png", dpi=160); plt.close()
res["per_driver_events_per_h"] = tab.round(2).to_dict("index")

# ---------- F5 speed histogram + 5 km/h
sp = df.ME_Car_speed_mean.dropna(); fig, ax = plt.subplots(figsize=(7.5, 3.2))
ax.hist(sp.clip(upper=120), bins=np.arange(0, 121, 2), color="#2a78d6"); ax.set_yscale("log")
ax.axvline(5, color=INK, lw=1.2); ax.text(6, ax.get_ylim()[1] * 0.6, "5 km/h (team threshold)", fontsize=9, color=INK)
ax.set_xlabel("ME_Car_speed_mean (km/h), minute mean"); ax.set_ylabel("minutes (log)")
ax.set_title("Where the 'moving' threshold sits in the speed distribution", loc="left", fontsize=11, color=INK)
fig.tight_layout(); fig.savefig(OUT + "f5_speed_threshold.png", dpi=160); plt.close()
sh = pd.cut(sp, [-0.001, 0.5, 1, 2, 3, 5, 10, 20, 50, 200]).value_counts(sort=False)
res["speed_bins_minutes"] = {str(k): int(v) for k, v in sh.items()}

# ---------- F6 drive_since_break
dsb = base["aux"].drive_since_break[mv]; fig, ax = plt.subplots(figsize=(7.5, 3.2))
ax.hist(dsb, bins=np.arange(0, 420, 10), color="#2a78d6")
top = ax.get_ylim()[1]
for x, t, y in [(120, "120 min: yawn (D3.6)", 0.88)]:
    ax.axvline(x, color=INK, lw=1.2); ax.text(x + 4, top * y, t, fontsize=9, color=INK)
ax.set_xlim(0, 420); ax.set_xlabel("drive_since_break (minutes)"); ax.set_ylabel("moving minutes")
ax.set_title("Cumulative driving since last complete break", loc="left", fontsize=11, color=INK)
fig.tight_layout(); fig.savefig(OUT + "f6_drive_since_break.png", dpi=160); plt.close()
res["drive_since_break_pct_ge120"] = round((dsb >= 120).mean() * 100, 1)

# ---------- F7 sensitivity: fatigue emission x tailgating definition
rows = []
for fe in ["episode", "first2", "per_minute"]:
    for tl in ["ge30", "dominant", "gt0"]:
        r_ = run(replace(Config(), fatigue_emit=fe, tailgating=tl))
        rows.append(dict(fatigue_emit=fe, tailgating=tl, events_per_h=round(sum(r_["rate"].values()), 2),
                         **{f"min_{k}": round(v, 1) for k, v in r_["per_min"].items()},
                         **{f"vday_{k}": round(v, 1) for k, v in r_["per_vd"].items()},
                         alerts_per_h=round(sum(r_["alr"].values()), 2), vday_with_alert_pct=round(r_["vd_alert"], 1)))
sens = pd.DataFrame(rows); sens.to_csv("sensitivity_fatigue_tailgating.csv", index=False)
fig, ax = plt.subplots(figsize=(7.5, 3.4)); FM = {"episode": "count per episode", "first2": "first 2 min of episode", "per_minute": "every minute"}; TM = {"ge30": "tailgating: Headway L3 >= 30 s", "dominant": "tailgating: L3 dominant", "gt0": "tailgating: L3 > 0"}
lab = [f"{FM[a]} | {TM[b]}" for a, b in zip(sens.fatigue_emit, sens.tailgating)]
left = np.zeros(len(sens))
for lvl in ["LOW", "MEDIUM", "HIGH"]:
    v = sens[f"vday_{lvl}"].values; ax.barh(lab[::-1], v[::-1], left=left[::-1], color=SEQ[lvl], edgecolor="white", linewidth=2, height=0.6, label=lvl); left += v
ax.set_xlim(0, 100); ax.set_xlabel("% of vehicle-days (highest status of the day)")
ax.legend(ncol=3, frameon=False, loc="lower center", bbox_to_anchor=(0.35, 1.0)); ax.grid(False)
fig.suptitle("Status per vehicle-day by counting method and tailgating definition", x=0.01, ha="left", fontsize=10, color="#52514e")
fig.tight_layout(); fig.savefig(OUT + "f7_sensitivity.png", dpi=160); plt.close()

# ---------- F8 one vehicle-day timeline (deterministic pick: median event count among days with HIGH and >= 4 h moving)
tot = sum(base["ev"][k].astype(int) for k in EV)
nev = tot[mv].groupby(df.vday[mv]).sum(); mvm = mv.groupby(df.vday).sum()
hi = (base["st"] == "HIGH").groupby(df.vday).any()
cand = nev[(mvm[nev.index] >= 240) & hi[nev.index]]
pick = cand.sort_values().index[len(cand) // 2]
g = df.index[(df.vday == pick) & mv]; g = g[np.argsort(df.ts[g].values)]
t = (df.ts[g] - df.ts[g].min()).dt.total_seconds().values / 3600
fig, (a0, a1) = plt.subplots(2, 1, figsize=(9, 3.9), sharex=True, gridspec_kw=dict(height_ratios=[3, 1]))
for i, k in enumerate(EV):
    m = base["ev"][k][g].values; a0.scatter(t[m], np.full(m.sum(), i), s=30, color=COL[k], edgecolor="white", linewidth=0.8, zorder=3)
a0.set_yticks(range(5)); a0.set_yticklabels(EV); a0.invert_yaxis()
a0.set_title(f"One vehicle-day: events and 10-min status ({len(g)} moving min, {int(cand[pick])} events)", loc="left", fontsize=11, color=INK)
for lvl in ["LOW", "MEDIUM", "HIGH"]:
    m = (base["st"][g] == lvl).values; a1.bar(t[m], 1, width=1/60, color=SEQ[lvl], label=lvl, linewidth=0)
a1.set_yticks([]); a1.set_xlabel("hours since first record of the day (gaps = engine off / parked)")
a1.legend(ncol=3, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.55), fontsize=8); a1.grid(False)
fig.tight_layout(); fig.savefig(OUT + "f8_timeline_one_day.png", dpi=160); plt.close()

json.dump(res, open("results.json", "w"), ensure_ascii=False, indent=1, default=str)
print(json.dumps({k: v for k, v in res.items() if k not in ("per_driver_events_per_h",)}, ensure_ascii=False, indent=1, default=str))
print(sens.to_string())
